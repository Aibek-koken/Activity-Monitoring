-- Sprint 4 rework: weekly/final versions, in-app annotations, correction pages,
-- rework accounting, and Chief Editor weekly availability.
-- V5 is already applied in local databases, so this is a new migration.

ALTER TABLE reviews ADD COLUMN review_kind VARCHAR(16) NOT NULL DEFAULT 'FINAL';
ALTER TABLE reviews ADD COLUMN week_start_date DATE;
ALTER TABLE reviews ADD COLUMN correction_pages INTEGER;

ALTER TABLE reviews ADD CONSTRAINT ck_reviews_kind
    CHECK (review_kind IN ('WEEKLY', 'FINAL'));
ALTER TABLE reviews ADD CONSTRAINT ck_reviews_week_start
    CHECK (
        (review_kind = 'WEEKLY' AND week_start_date IS NOT NULL)
        OR (review_kind = 'FINAL' AND week_start_date IS NULL)
    );
ALTER TABLE reviews ADD CONSTRAINT ck_reviews_correction_pages
    CHECK (correction_pages IS NULL OR (correction_pages > 0 AND correction_pages <= 10000));

CREATE INDEX idx_reviews_activity_kind_week
    ON reviews (activity_id, review_kind, week_start_date);

CREATE TABLE review_annotations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id BIGINT NOT NULL REFERENCES reviews (id) ON DELETE CASCADE,
    page_number INTEGER NOT NULL,
    kind VARCHAR(16) NOT NULL,
    rects_json TEXT NOT NULL,
    quoted_text TEXT,
    comment TEXT,
    suggested_replacement TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_review_annotations_page CHECK (page_number > 0 AND page_number <= 10000),
    CONSTRAINT ck_review_annotations_kind CHECK (kind IN ('HIGHLIGHT', 'STRIKETHROUGH', 'RECT')),
    CONSTRAINT ck_review_annotations_rects CHECK (CHAR_LENGTH(rects_json) BETWEEN 2 AND 20000),
    CONSTRAINT ck_review_annotations_content CHECK (
        quoted_text IS NOT NULL
        OR comment IS NOT NULL
        OR suggested_replacement IS NOT NULL
    )
);

CREATE INDEX idx_review_annotations_review_page
    ON review_annotations (review_id, page_number, id);

ALTER TABLE work_records ADD COLUMN rework_pages NUMERIC(10, 2) NOT NULL DEFAULT 0;
ALTER TABLE work_records ADD COLUMN rework_review_id BIGINT REFERENCES reviews (id) ON DELETE SET NULL;

ALTER TABLE work_records ADD CONSTRAINT ck_work_records_rework_pages
    CHECK (rework_pages >= 0 AND rework_pages <= 1000);
ALTER TABLE work_records ADD CONSTRAINT ck_work_records_rework_pair
    CHECK (
        (rework_pages = 0 AND rework_review_id IS NULL)
        OR (rework_pages > 0 AND rework_review_id IS NOT NULL)
    );

CREATE INDEX idx_work_records_rework_review
    ON work_records (rework_review_id);

CREATE TABLE chief_editor_availability (
    user_id BIGINT PRIMARY KEY REFERENCES app_users (id) ON DELETE CASCADE,
    weekly_hours NUMERIC(6, 2) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_chief_editor_availability_hours
        CHECK (weekly_hours > 0 AND weekly_hours <= 168)
);

ALTER TABLE notifications DROP CONSTRAINT ck_notifications_type;
ALTER TABLE notifications DROP CONSTRAINT ck_notifications_activity;

ALTER TABLE notifications ADD CONSTRAINT ck_notifications_type CHECK (
    type IN (
        'DAILY_RECORD_REMINDER',
        'WEEKLY_ESTIMATE_REMINDER',
        'WEEKLY_SUBMISSION_REMINDER',
        'CORRECTION_REQUESTED'
    )
);
ALTER TABLE notifications ADD CONSTRAINT ck_notifications_activity CHECK (
    (type = 'DAILY_RECORD_REMINDER' AND activity_id IS NULL)
    OR (type IN ('WEEKLY_ESTIMATE_REMINDER', 'WEEKLY_SUBMISSION_REMINDER', 'CORRECTION_REQUESTED')
        AND activity_id IS NOT NULL)
);
