CREATE TABLE work_record_edit_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_record_id BIGINT NOT NULL REFERENCES work_records (id) ON DELETE CASCADE,
    active_work_record_id BIGINT UNIQUE REFERENCES work_records (id) ON DELETE CASCADE,
    translator_id BIGINT NOT NULL REFERENCES app_users (id),
    project_manager_id BIGINT NOT NULL REFERENCES app_users (id),
    reason VARCHAR(1000) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    decision_comment VARCHAR(1000),
    requested_at TIMESTAMP WITH TIME ZONE NOT NULL,
    decided_at TIMESTAMP WITH TIME ZONE,
    used_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_work_record_edit_requests_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'USED')),
    CONSTRAINT ck_work_record_edit_requests_reason CHECK (CHAR_LENGTH(TRIM(reason)) > 0),
    CONSTRAINT ck_work_record_edit_requests_active CHECK (
        (status IN ('PENDING', 'APPROVED') AND active_work_record_id = work_record_id)
        OR (status IN ('REJECTED', 'USED') AND active_work_record_id IS NULL)
    )
);
CREATE INDEX idx_work_record_edit_requests_manager ON work_record_edit_requests (project_manager_id, status, requested_at DESC);
CREATE INDEX idx_work_record_edit_requests_translator ON work_record_edit_requests (translator_id, requested_at DESC);
