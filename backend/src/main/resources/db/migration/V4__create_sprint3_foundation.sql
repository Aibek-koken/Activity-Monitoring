CREATE TABLE weekly_estimates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id BIGINT NOT NULL REFERENCES activities (id) ON DELETE CASCADE,
    translator_id BIGINT NOT NULL REFERENCES app_users (id),
    week_start_date DATE NOT NULL,
    remaining_text_volume NUMERIC(14, 2) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_weekly_estimates_activity_week UNIQUE (activity_id, week_start_date),
    CONSTRAINT ck_weekly_estimates_remaining CHECK (remaining_text_volume >= 0)
);

CREATE INDEX idx_weekly_estimates_activity_week ON weekly_estimates (activity_id, week_start_date);
CREATE INDEX idx_weekly_estimates_translator_week ON weekly_estimates (translator_id, week_start_date);

CREATE TABLE project_chief_editors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    chief_editor_id BIGINT NOT NULL REFERENCES app_users (id),
    is_responsible BOOLEAN NOT NULL DEFAULT FALSE,
    responsible_project_id BIGINT UNIQUE REFERENCES projects (id) ON DELETE CASCADE,
    CONSTRAINT uq_project_chief_editors_project_editor UNIQUE (project_id, chief_editor_id),
    CONSTRAINT ck_project_chief_editors_responsible CHECK (
        (is_responsible = TRUE AND responsible_project_id = project_id)
        OR (is_responsible = FALSE AND responsible_project_id IS NULL)
    )
);

CREATE INDEX idx_project_chief_editors_editor ON project_chief_editors (chief_editor_id);

CREATE TABLE reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id BIGINT NOT NULL REFERENCES activities (id) ON DELETE CASCADE,
    chief_editor_id BIGINT NOT NULL REFERENCES app_users (id),
    cycle_number INTEGER NOT NULL,
    submitted_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    checking_date DATE,
    result VARCHAR(32),
    mistakes_notes TEXT,
    CONSTRAINT uq_reviews_activity_cycle UNIQUE (activity_id, cycle_number),
    CONSTRAINT ck_reviews_cycle_positive CHECK (cycle_number > 0)
);

CREATE INDEX idx_reviews_chief_editor_submitted ON reviews (chief_editor_id, submitted_at);

CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    activity_id BIGINT REFERENCES activities (id) ON DELETE CASCADE,
    type VARCHAR(40) NOT NULL,
    period_date DATE NOT NULL,
    dedupe_key VARCHAR(160) NOT NULL UNIQUE,
    message VARCHAR(500) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    read_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_notifications_type CHECK (
        type IN ('DAILY_RECORD_REMINDER', 'WEEKLY_ESTIMATE_REMINDER')
    ),
    CONSTRAINT ck_notifications_activity CHECK (
        (type = 'DAILY_RECORD_REMINDER' AND activity_id IS NULL)
        OR (type = 'WEEKLY_ESTIMATE_REMINDER' AND activity_id IS NOT NULL)
    )
);

CREATE INDEX idx_notifications_user_unread ON notifications (user_id, is_read, created_at);
